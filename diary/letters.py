"""Шаблоны обращений: при отказе в обследовании и при ошибочной записи в выписке ОМС.

Текст собирается только из плана и выбранных вариантов. ФИО и номер полиса не
подставляются: в тексте остаются места [ФИО] и [номер полиса], пациент
заполняет их сам. Письмо нигде не сохраняется и никуда не отправляется.
"""

from datetime import date

REASONS = {
    "no_ticket": "мне не выдали талон и не записали на обследование",
    "paid": "мне предложили пройти обследование платно или направили в платное отделение",
    "not_entitled": "мне сказали, что это обследование мне не положено",
    "other": "мне отказали в проведении обследования",
}
ADDRESSEES = {
    "chief": "Главному врачу [название поликлиники]",
    "smo": "В страховую медицинскую организацию [название, указано на полисе ОМС]",
}
FROM = "от [ФИО]\nполис ОМС № [номер полиса]\nтелефон для связи: [телефон]"
SIGN = "Дата: ____________          Подпись: ____________"
LAW_326 = ("По ст. 16 Федерального закона от 29.11.2010 № 326-ФЗ «Об обязательном медицинском страховании "
           "в Российской Федерации» застрахованные лица имеют право на бесплатную медицинскую помощь "
           "в объёме базовой программы ОМС.")
LAW_323 = ("По ч. 1 ст. 80 Федерального закона от 21.11.2011 № 323-ФЗ «Об основах охраны здоровья граждан "
           "в Российской Федерации» медицинская помощь в рамках программы государственных гарантий "
           "оказывается без взимания платы.")


def _fmt(d):
    return d.strftime("%d.%m.%Y")


def _past_date(value, today):
    try:
        d = date.fromisoformat(str(value))
    except ValueError:
        raise ValueError("Укажите дату в формате ГГГГ-ММ-ДД.")
    if d > today or d.year < 2000:
        raise ValueError("Укажите прошедшую дату.")
    return d


def refusal_letter(item, reason, when, addressee, today):
    """Заявление, если в поликлинике отказали в положенном обследовании или прививке."""
    if reason not in REASONS:
        raise ValueError("Выберите, что произошло.")
    if addressee not in ADDRESSEES:
        raise ValueError("Выберите, кому адресовано заявление.")
    d = _past_date(when, today)
    what = ("Эта прививка входит в национальный календарь профилактических прививок" if item["kind"] == "vaccine"
            else "Это обследование входит в профилактический медицинский осмотр и диспансеризацию")
    title = f"«{item['title']}»"
    src = item["source"]
    laws = LAW_326 + ("\n\n" + LAW_323 if reason == "paid" else "")
    ask = ("1. Организовать мне проведение {t} бесплатно по полису ОМС.\n"
           "2. Дать письменный ответ на это заявление.").format(t=title)
    if addressee == "smo":
        ask = ("1. Провести проверку и защитить мои права как застрахованного лица.\n"
               "2. Помочь организовать проведение {t} бесплатно по полису ОМС.\n"
               "3. Сообщить мне о результатах письменно.").format(t=title)
    return "\n\n".join([
        ADDRESSEES[addressee] + "\n" + FROM,
        "ЗАЯВЛЕНИЕ",
        f"{_fmt(d)} я обратился(-ась) в поликлинику по месту прикрепления, чтобы пройти: {title}. "
        f"При этом {REASONS[reason]}.",
        f"{what} и положено мне бесплатно (кому положено: {item['who']}). "
        f"Основание: {src['clause']} {src.get('short') or ''} ({src['title']}).".replace("  ", " "),
        laws,
        "Прошу:\n" + ask,
        SIGN,
    ])


def dispute_letter(title, when, today):
    """Заявление в страховую, если в выписке есть услуга, которую человек не получал."""
    d = _past_date(when, today)
    return "\n\n".join([
        ADDRESSEES["smo"] + "\n" + FROM,
        "ЗАЯВЛЕНИЕ",
        "В сведениях об оказанных мне медицинских услугах и их стоимости (получены через Госуслуги) указано, "
        f"что {_fmt(d)} мне было проведено: «{title}». Эту услугу я не получал(а).",
        "Прошу проверить обоснованность оплаты этой услуги из средств ОМС и сообщить мне о результатах письменно.",
        SIGN,
    ])
