# Расширение по первым байтам файла. Имя файла не учитывается: его легко подменить.
FILE_SIGNATURES = (
    (b"%PDF-", "pdf", "application/pdf"),
    (b"\xff\xd8\xff", "jpg", "image/jpeg"),
    (b"\x89PNG\r\n\x1a\n", "png", "image/png"),
)
CONTENT_TYPES = {ext: ctype for _, ext, ctype in FILE_SIGNATURES}


def detect_file_type(raw):
    """'pdf' | 'jpg' | 'png' или None, если файл другого типа."""
    for magic, ext, _ in FILE_SIGNATURES:
        if raw.startswith(magic):
            return ext
    return None


def consent_record(today=None):
    return {"version": CONSENT_VERSION, "date": (today or date.today()).isoformat()}


# --- обезличивание вопроса ассистенту ----------------------------------------

_REDACTIONS = (
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"), "[e-mail]"),
    (re.compile(r"\b\d{3}-\d{3}-\d{3}[ -]?\d{2}\b"), "[СНИЛС]"),
    (re.compile(r"(?<!\d)\d{16}(?!\d)"), "[номер полиса]"),
    (re.compile(r"(?<![\d.])(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)"), "[телефон]"),
    (re.compile(r"(?<!\d)\d{4}\s?\d{6}(?!\d)"), "[номер паспорта]"),
)


def redact(text):
    """Убирает из текста телефоны, e-mail, СНИЛС, номер полиса ОМС и паспорта."""
    for pattern, label in _REDACTIONS:
        text = pattern.sub(label, text)
    return text


# --- выгрузка своих данных ---------------------------------------------------

def export_archive(storage):
    """ZIP со всеми данными пользователя: профиль и отметки, файлы, журнал запросов к нейросети."""
    state = storage.load()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("README.txt", (
            "Выгрузка данных из сервиса «CheckUp Track»\n"
            f"Дата выгрузки: {datetime.now().strftime('%d.%m.%Y %H:%M')}\n\n"
            "state.json — профиль, согласие, отметки о пройденных обследованиях, показатели и приписки\n"
            "files/ — загруженные результаты обследований\n"
            "llm_log.jsonl — вопросы, отправленные в YandexGPT (если он был подключён)\n"))
        zf.writestr("state.json", json.dumps(state, ensure_ascii=False, indent=2))
        if storage.files_dir.exists():
            for path in sorted(storage.files_dir.iterdir()):
                if path.is_file():
                    zf.write(path, f"files/{path.name}")
        log = storage.user_dir / "llm_log.jsonl"
        if log.exists():
            zf.write(log, "llm_log.jsonl")
    return buf.getvalue()


